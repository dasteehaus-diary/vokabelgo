function deleteTrackById(chan, id, title = 'bài hát'){
  const list = getPlaylist(chan);
  const track = list.find(t => t.id === id);
  const trackTitle = track ? track.title : title;

  // Check user custom tracks
  const userIdx = (userTracks[chan] || []).findIndex(t => t.id === id);
  if(userIdx !== -1){
    userTracks[chan].splice(userIdx, 1);
    if(chan === 'radio') saveCustomPodcasts();
  } else {
    // Default collection track
    if(!deletedTrackIds.includes(id)){
      deletedTrackIds.push(id);
      saveDeletedTracks();
    }
  }

  showRetroToast(`Đã xóa "${trackTitle}" khỏi danh sách!`, '🗑️');

  // Adjust index if needed
  const newList = getPlaylist(chan);
  if(channelTrackIndices[chan] >= newList.length){
    channelTrackIndices[chan] = Math.max(0, newList.length - 1);
  }

  if(chan === currentChannel){
    if(isBoomboxPlaying && newList.length > 0){
      playCurrentChannel();
    } else if(newList.length === 0){
      audioPlayer.pause();
      stopRainAmbient();
      isBoomboxPlaying = false;
      updateTapeUI();
    } else {
      updateTapeUI();
    }
  }

  renderPlaylistModal(chan);
}

