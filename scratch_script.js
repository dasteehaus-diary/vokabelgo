function startMatchGame(){
  clearInterval(matchTimerInterval);
  document.getElementById('matchTimer').textContent = '00:00.0';
  document.getElementById('matchVictory').classList.add('hidden');
  matchSelected = null;
  matchPairsFound = 0;

  let pool = (filtered && filtered.length >= 6 ? filtered : allCards());
  const concisePool = pool.filter(c => !c.term.includes('?') && c.term.length <= 45 && c.meaning.length <= 55);
  if(concisePool.length >= 6){
    pool = concisePool;
  }
  if(!pool.length){
    document.getElementById('matchGrid').innerHTML = '<div style="grid-column:1/-1;text-align:center;padding:30px;color:var(--muted)">Chưa có thẻ nào để chơi ghép cặp.</div>';
    return;
  }
  const picked = rand(pool, Math.min(6, pool.length));
  const cardsData = [];
  picked.forEach(c => {
    cardsData.push({ id: c.id, text: c.term, type: 'de' });
    cardsData.push({ id: c.id, text: getPureMeaning(c.meaning), type: 'vi' });
  });
  const shuffled = rand(cardsData, cardsData.length);
  const grid = document.getElementById('matchGrid');
  grid.innerHTML = '';
  
  shuffled.forEach(item => {
    const el = document.createElement('div');
    el.className = 'match-card';
    el.textContent = item.text;
    el.dataset.id = item.id;
    el.dataset.type = item.type;
    el.onclick = () => onMatchCardClick(el, item);
    grid.appendChild(el);
  });

  matchStartTime = Date.now();
  matchTimerInterval = setInterval(() => {
    const diff = (Date.now() - matchStartTime) / 1000;
    const m = Math.floor(diff / 60);
    const s = (diff % 60).toFixed(1);
    document.getElementById('matchTimer').textContent = `${m < 10 ? '0' : ''}${m}:${s < 10 ? '0' : ''}${s}`;
  }, 100);
}

function onMatchCardClick(el, item){
  if(el.classList.contains('matched') || el.classList.contains('wrong')) return;
  getAudioContext();
  
  if(!matchSelected){
    matchSelected = { el, item };
    el.classList.add('selected');
    playMechanicalClick();
    return;
  }

  if(matchSelected.el === el){
    el.classList.remove('selected');
    matchSelected = null;
    return;
  }

  const prev = matchSelected;
  if(prev.item.id === item.id && prev.item.type !== item.type){
    // Match correct!
    prev.el.classList.remove('selected');
    prev.el.classList.add('matched');
    el.classList.add('matched');
    matchSelected = null;
    matchPairsFound++;
    playMatchTing();

    if(matchPairsFound >= 6){
      clearInterval(matchTimerInterval);
      const totalSec = ((Date.now() - matchStartTime) / 1000).toFixed(1);
      const oldBest = parseFloat(localStorage.getItem(MATCH_BEST_KEY) || '99999');
      let isNewRecord = false;
      if(parseFloat(totalSec) < oldBest){
        localStorage.setItem(MATCH_BEST_KEY, totalSec);
        isNewRecord = true;
        updateMatchBestDisplay();
      }
      document.getElementById('matchVictoryText').innerHTML = `Thời gian hoàn thành: <b>${totalSec} giây</b>!` + (isNewRecord ? '<br><span style="color:#d97706;font-weight:bold">🏆 KỶ LỤC MỚI CỦA BẠN!</span>' : '');
      document.getElementById('matchVictory').classList.remove('hidden');
    }
  } else {
    // Mismatch
    prev.el.classList.add('wrong');
    el.classList.add('wrong');
    playMatchWrong();
    matchSelected = null;
    setTimeout(() => {
      prev.el.classList.remove('selected', 'wrong');
      el.classList.remove('selected', 'wrong');
    }, 420);
  }
}

