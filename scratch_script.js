let calendarYear = new Date().getFullYear();
let calendarMonth = new Date().getMonth(); // 0-indexed

function getCheckinHistory(){
  try {
    const raw = localStorage.getItem('vokabelgo_checkin_history');
    if(raw){
      let parsed = JSON.parse(raw);
      // Auto-clean dummy sample entries (init_1, init_2, init_3, Minh Đức, Mai Lan)
      const cleaned = parsed.filter(item => !String(item.id).startsWith('init_') && item.nickname !== 'Minh Đức' && item.nickname !== 'Mai Lan');
      if(cleaned.length !== parsed.length){
        localStorage.setItem('vokabelgo_checkin_history', JSON.stringify(cleaned));
      }
      return cleaned;
    }
  } catch(e){}
  
  // Clean start - no dummy sample entries
  return [];
}

function saveCheckinEntry(entry){
  const history = getCheckinHistory();
  history.unshift(entry);
  try {
    localStorage.setItem('vokabelgo_checkin_history', JSON.stringify(history));
  } catch(e){}
}

function calculateStreak(history){
  const todayStr = new Date().toISOString().slice(0, 10);
  const yesterdayStr = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
  
  const dates = new Set(history.map(h => h.date));
  let streak = 0;
  let checkDate = new Date();
  
  if(!dates.has(todayStr)){
    if(!dates.has(yesterdayStr)) return 0;
    checkDate = new Date(Date.now() - 86400000);
  }
  
  while(true){
    const dStr = checkDate.toISOString().slice(0, 10);
    if(dates.has(dStr)){
      streak++;
      checkDate = new Date(checkDate.getTime() - 86400000);
    } else {
      break;
    }
  }
  return streak;
}

function renderCheckinCalendar(){
  const history = getCheckinHistory();
  const streak = calculateStreak(history);
  const streakEl = document.getElementById('streakCount');
  if(streakEl) streakEl.textContent = `${streak} ngày liên tiếp`;

  const curMonthHistory = history.filter(h => {
    const d = new Date(h.date);
    return d.getFullYear() === calendarYear && d.getMonth() === calendarMonth;
  });
  const uniqueDaysThisMonth = new Set(curMonthHistory.map(h => h.date)).size;
  const monthCountEl = document.getElementById('monthCheckinCount');
  if(monthCountEl) monthCountEl.textContent = `${uniqueDaysThisMonth} ngày học`;

  const titleEl = document.getElementById('calendarTitle');
  if(titleEl) titleEl.textContent = `Tháng ${calendarMonth + 1} / ${calendarYear}`;

  const grid = document.getElementById('calendarGrid');
  if(!grid) return;
  grid.innerHTML = '';

  const firstDay = new Date(calendarYear, calendarMonth, 1);
  let startOffset = firstDay.getDay() - 1;
  if(startOffset === -1) startOffset = 6;

  const daysInMonth = new Date(calendarYear, calendarMonth + 1, 0).getDate();
  const daysInPrevMonth = new Date(calendarYear, calendarMonth, 0).getDate();

  for(let i = startOffset - 1; i >= 0; i--){
    const cell = document.createElement('div');
    cell.className = 'cal-day other-month';
    cell.textContent = daysInPrevMonth - i;
    grid.appendChild(cell);
  }

  const todayStr = new Date().toISOString().slice(0, 10);
  const dateMap = {};
  history.forEach(h => {
    if(!dateMap[h.date]) dateMap[h.date] = h;
  });

  for(let day = 1; day <= daysInMonth; day++){
    const cell = document.createElement('div');
    cell.className = 'cal-day';
    const dayStr = `${calendarYear}-${String(calendarMonth + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
    
    if(dayStr === todayStr) cell.classList.add('today');

    if(dateMap[dayStr]){
      cell.classList.add('checked');
      const item = dateMap[dayStr];
      const emojiSrc = `img/emojis/emoji_${String(item.emojiId || 1).padStart(2, '0')}.png`;
      cell.innerHTML = `
        <span class="cal-num">${day}</span>
        <img src="${emojiSrc}" alt="${esc(item.emojiName || '')}" class="cal-sticker" title="${esc(item.nickname)}: ${esc(item.note)}">
      `;
    } else {
      cell.innerHTML = `<span class="cal-num">${day}</span>`;
    }
    grid.appendChild(cell);
  }

  renderGuestbook();
}

