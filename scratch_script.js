async function startKinoDubbingProcess(){
  if(kinoIsDubbing){
    stopKinoDubbing();
    return;
  }

  try {
    // Studio-quality microphone constraints: disable harsh choke filters, enable auto-gain boost
    const stream = await navigator.mediaDevices.getUserMedia({
      audio: {
        echoCancellation: false,
        noiseSuppression: false,
        autoGainControl: true,
        channelCount: 1
      }
    });
    runKinoCountdown(() => runKinoDubbingRecording(stream));
  } catch(err){
    // Fallback if specific constraints not supported
    try {
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      runKinoCountdown(() => runKinoDubbingRecording(stream));
    } catch(e2){
      alert("Không thể mở Micro. Xin vui lòng cho phép quyền truy cập Micro trên trình duyệt để luyện lồng tiếng!");
      console.error("Mic error:", e2);
    }
  }
}

