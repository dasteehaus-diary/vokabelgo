function getPureMeaning(m){
  if(!m) return '';
  let s = String(m).trim();
  if(s.includes('=')){
    const parts = s.split(';').map(seg => {
      const idx = seg.indexOf('=');
      return idx !== -1 ? seg.slice(idx + 1).trim() : seg.trim();
    }).filter(Boolean);
    if(parts.length) s = parts.join('; ');
  }
  s = s.replace(/\s*\([^)]*(?:đồng nghĩa|synonym|trái nghĩa|antonym)[^)]*\)/gi, '').trim();
  s = s.replace(/^(?:từ đồng nghĩa|đồng nghĩa|synonym|trái nghĩa|antonym)\s*:\s*/gi, '').trim();
  return s;
}

function newQuestion(){
  if(!filtered.length) return;
  mcqLocked = false;
  const c = current();
  document.getElementById('mcqQ').textContent = c.term;
  const fb = document.getElementById('mcqFeedback');
  fb.className = 'feedback';
  fb.textContent = '';
  
  const isQuestionCard = c.term.includes('?') || (c.tags && c.tags.includes('Inhalt'));
  const targetMeaning = getPureMeaning(c.meaning);
  const targetLen = targetMeaning.length;

  // 1. Filter candidates from current deck (filtered) first for topic relevance
  let candidates = filtered.filter(x => x.id !== c.id && getPureMeaning(x.meaning) !== targetMeaning);

  // Match card nature: Q&A reading cards vs standard vocabulary
  let matchingType = candidates.filter(x => {
    const isQA = x.term.includes('?') || (x.tags && x.tags.includes('Inhalt'));
    return isQA === isQuestionCard;
  });

  if(matchingType.length >= 3){
    candidates = matchingType;
  }

  // 2. If not enough candidates in same deck, borrow from allCards() with matching type
  if(candidates.length < 3){
    const otherPool = allCards().filter(x => x.id !== c.id && getPureMeaning(x.meaning) !== targetMeaning && (x.term.includes('?') === isQuestionCard));
    candidates = [...candidates, ...otherPool];
  }

  // 3. Sort by length similarity to target meaning to avoid jarring length mismatches
  candidates.sort((a, b) => Math.abs(getPureMeaning(a.meaning).length - targetLen) - Math.abs(getPureMeaning(b.meaning).length - targetLen));
  
  // Pick top closest candidates and randomize 3 from them
  const poolClosest = candidates.slice(0, Math.max(8, candidates.length));
  let ds = rand(poolClosest, 3);
  
  // Fallback if somehow ds < 3
  if(ds.length < 3){
    const extra = allCards().filter(x => x.id !== c.id && getPureMeaning(x.meaning) !== targetMeaning && !ds.some(d => d.id === x.id));
    ds = [...ds, ...rand(extra, 3 - ds.length)];
  }

  let opts = rand([c, ...ds], 4);
  const wrap = document.getElementById('mcqOptions');
  wrap.innerHTML = '';
  const letters = ['A', 'B', 'C', 'D'];
  opts.forEach((o, i) => {
    const b = document.createElement('button');
    b.className = 'option';
    b.innerHTML = `<span class="opt-badge">${letters[i]}</span><span class="opt-text">${esc(getPureMeaning(o.meaning))}</span>`;
    b.onclick = () => {
      if(mcqLocked) return;
      mcqLocked = true;
      [...wrap.children].forEach((btn, idx) => {
        if(opts[idx].id === c.id) btn.classList.add('correct');
      });
      if(o.id === c.id){
        playMatchSound();
        fb.innerHTML = `🎉 <b>Chính xác!</b> ${esc(c.term)} = ${esc(getPureMeaning(c.meaning))}`;
        fb.style.background = 'var(--c-matcha)';
        fb.style.color = '#234010';
        fb.style.borderColor = 'var(--c-olive)';
        progress[c.id] = 'known';
      } else {
        try{ if(typeof playMatchWrong === 'function') playMatchWrong(); }catch(e){}
        b.classList.add('wrong');
        fb.innerHTML = `💡 <b>Chưa đúng rồi.</b> Đáp án đúng là: <b>${esc(getPureMeaning(c.meaning))}</b>`;
        fb.style.background = '#FDE8E4';
        fb.style.color = '#9A2C05';
        fb.style.borderColor = 'var(--c-terracotta)';
        progress[c.id] = 'hard';
      }
      fb.classList.add('show');
      saveProgress();
      updateStats();
    };
    wrap.appendChild(b);
  });
}
